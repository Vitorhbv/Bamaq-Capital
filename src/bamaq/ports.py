"""Interfaces owned by the application, implemented by external adapters."""

from collections.abc import Callable
from datetime import datetime
from typing import Protocol, Self

from bamaq.domain import FailedMessage, Job, OutboxEvent, Status, Transaction


class Clock(Protocol):
    def now(self) -> datetime: ...


class IdGenerator(Protocol):
    def new(self) -> str: ...


class RiskAnalysis(Protocol):
    def analyze(self, transaction: Transaction) -> Status: ...


class Publisher(Protocol):
    def publish(self, event: OutboxEvent) -> None:
        """Return only after a broker delivery acknowledgement."""
        ...


class TransactionRepository(Protocol):
    def get(self, transaction_id: str, *, lock: bool = False) -> Transaction | None: ...
    def by_key(self, key: str) -> Transaction | None: ...
    def add(self, transaction: Transaction) -> None: ...


class JobRepository(Protocol):
    def by_event(self, event_id: str) -> Job | None: ...
    def by_generation(self, transaction_id: str, generation: int) -> Job | None: ...
    def get(self, job_id: str, *, lock: bool = False) -> Job | None: ...
    def claimable(self, now: datetime) -> Job | None: ...
    def add(self, job: Job) -> None: ...


class OutboxRepository(Protocol):
    def add(self, event: OutboxEvent) -> None: ...
    def oldest_pending(self) -> OutboxEvent | None: ...


class FailureRepository(Protocol):
    def add(self, failure: FailedMessage) -> None: ...
    def get(self, failure_id: str, *, lock: bool = False) -> FailedMessage | None: ...
    def by_source(self, topic: str, partition: int, offset: int) -> FailedMessage | None: ...
    def list_recent(self, limit: int) -> list[FailedMessage]: ...
    def for_generation(self, transaction_id: str, generation: int) -> list[FailedMessage]: ...


class UnitOfWork(Protocol):
    transactions: TransactionRepository
    jobs: JobRepository
    outbox: OutboxRepository
    failures: FailureRepository

    def __enter__(self) -> Self: ...
    def __exit__(self, *args: object) -> None: ...
    def commit(self) -> None: ...


UowFactory = Callable[[], UnitOfWork]
